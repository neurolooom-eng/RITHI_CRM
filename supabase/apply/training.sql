-- ---- "I have read and understood" --------------------------------------------
-- The trainee's OWN assignment only, found by their sign-in address. DEFINER
-- with the ownership test inside: a plain UPDATE policy for trainees would let
-- them change the due date or cancel their own training too.
create or replace function public.acknowledge_training(p_id bigint)
returns timestamptz language plpgsql security definer set search_path = public as $$
declare t timestamptz;
begin
  update public.training_assignments a
     set acknowledged_at = coalesce(a.acknowledged_at, now())
   where a.id = p_id and not a.cancelled
     and exists (select 1 from public.user_directory d
                  where d.id = a.dir_id
                    and ( (btrim(coalesce(d.email, '')) <> '' and lower(d.email) = lower(auth.email()))
                       or (btrim(coalesce(d.gmail, '')) <> '' and lower(d.gmail) = lower(auth.email())) ))
  returning a.acknowledged_at into t;
  if t is null then
    raise exception 'This training is not assigned to you, or it was cancelled.' using errcode = '42501';
  end if;
  return t;
end $$;
