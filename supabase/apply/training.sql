-- ---- the state of every assignment -------------------------------------------
-- COMPLETE = attended a session on the same document (or the same topic, where
-- there is no document) without a Fail, OR acknowledged reading it with no
-- Fail recorded. A Fail keeps it open ("Failed - retrain") until a session is
-- attended without one. security_invoker: the caller's own policies bound it.
create or replace view public.training_status with (security_invoker = on) as
select a.id, a.dir_id, d.name as person, d.designation, d.department, d.region,
       a.document_id, doc.doc_no, doc.revision, a.topic, a.due_date, a.assigned_at,
       a.assigned_by_name, a.acknowledged_at, a.cancelled, a.cancel_reason,
       ok.session_date as attended_on,
       case
         when a.cancelled then 'Cancelled'
         when ok.session_date is not null then 'Completed'
         when a.acknowledged_at is not null and not coalesce(bad.failed, false) then 'Completed'
         when coalesce(bad.failed, false) then 'Failed - retrain'
         when a.due_date is not null and a.due_date < current_date then 'Overdue'
         else 'Pending'
       end as status,
       case
         when a.cancelled then null
         when ok.session_date is not null then ok.session_date::timestamptz
         when a.acknowledged_at is not null and not coalesce(bad.failed, false) then a.acknowledged_at
       end as completed_at
  from public.training_assignments a
  join public.user_directory d on d.id = a.dir_id
  left join public.documents doc on doc.id = a.document_id
  left join lateral (
    select min(s.session_date) as session_date
      from public.training_attendance t
      join public.training_sessions s on s.id = t.session_id
     where t.dir_id = a.dir_id and t.attended and t.assessment <> 'Fail'
       and ( (a.document_id is not null and s.document_id = a.document_id)
          or (a.document_id is null and lower(btrim(s.topic)) = lower(btrim(a.topic))) )
  ) ok on true
  left join lateral (
    select true as failed
      from public.training_attendance t
      join public.training_sessions s on s.id = t.session_id
     where t.dir_id = a.dir_id and t.assessment = 'Fail'
       and ( (a.document_id is not null and s.document_id = a.document_id)
          or (a.document_id is null and lower(btrim(s.topic)) = lower(btrim(a.topic))) )
     limit 1
  ) bad on true;
grant select on public.training_status to authenticated;

