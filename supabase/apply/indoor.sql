      or public.has_perm('indoor.qc')      or public.has_perm('indoor.dispatch')
      or public.has_perm('indoor.condemn'));

-- NO DELETE POLICY, and that is the same rule 0049 sets for consumption: a
-- quality record is not deleted. A job raised in error is closed with the
-- reason in its own words, so the register says what happened rather than
-- silently no longer mentioning a customer's machine.

-- The three child tables follow the parent: reading is the module right,
-- writing asks for indoor.work -- with harvested parts additionally gated by the
-- decontamination trigger above.
do $$
declare t text;
begin
  foreach t in array array['indoor_job_accessories', 'indoor_job_parts', 'indoor_job_checks'] loop
