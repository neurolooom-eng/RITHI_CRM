-- ---------------------------------------------------------------------------
-- THE HARD GATE — nothing is harvested from a unit that has not been cleaned.
--
-- The one rule in this file that BLOCKS rather than warns, and the plan says so
-- in as many words. Everything else here is a record; this is a person putting
-- their hands inside a device that has been in a hospital. WI/SER/01 comes
-- first, and the register is where that is provable.
-- ---------------------------------------------------------------------------
create or replace function public.indoor_job_parts_guard()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_ok boolean;
begin
  select decontaminated into v_ok from public.indoor_jobs where id = new.job_id;
  if not coalesce(v_ok, false) then
    raise exception 'the unit has not been decontaminated -- nothing is harvested from it yet (WI/SER/01, 4.5.3)'
      using errcode = '23514';
  end if;
  return new;
end $$;
