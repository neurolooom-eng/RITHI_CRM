  adverse_effect_assessed boolean,
  adverse_effect_note    text not null default '',
  reverified_by          text not null default '',
  reverified_at          timestamptz,
  reverification_result  text check (reverification_result in ('Pass', 'Fail')),
  disposition            text check (disposition in ('Released', 'Scrapped')),

  -- ---- Salvage (SR-017) --------------------------------------------------
  condemned_reason text not null default '',
  condemned_by     uuid,
  condemned_at     timestamptz,
  -- The hard gate. Nobody opens a used medical device before it is cleaned;
  -- enforced on the harvest rows below rather than warned about.
  decontaminated   boolean not null default false,
  disposal_method  text not null default '',
  disposal_ref     text not null default '',
  customer_informed boolean not null default false,

  -- ---- Pre-delivery inspection (SR-003 / SR-006 / SR-020) ----------------
  source_ref       text not null default '',
  checklist_ref    text not null default '',
  checklist_rev    text not null default '',
  firmware_version text not null default '',
  accessories_per_packing_list boolean,
  -- "Pass with observation" is what stops a real finding being rounded up to
  -- Pass. A Fail does not leave the workshop.
  pdi_result       text check (pdi_result in ('Pass', 'Pass with observation', 'Fail')),
  released_by      uuid,
  released_at      timestamptz,
  held_reason      text not null default '',

  -- ---- Demo --------------------------------------------------------------
  demo_for_party   text not null default '',
  requested_by     text not null default '',
  expected_out     date,
  expected_return  date,
  actual_out       date,
  actual_return    date,
  custody_holder   text not null default '',
  condition_out    text not null default '',
  condition_back   text not null default '',
  consumables_used text not null default '',
  demo_outcome     text check (demo_outcome in ('Converted', 'Returned', 'Damaged', 'Lost')),
  sale_ref         text not null default '',

  -- ---- Other -------------------------------------------------------------
  -- "Other" with no description is a hole in the record, so the constraint is
  -- on the table and not on the form.
  activity_note    text not null default '',

  created_by    uuid,
  created_at    timestamptz not null default now(),
  updated_by    uuid,
  updated_at    timestamptz not null default now(),

