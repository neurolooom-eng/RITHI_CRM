-- WHO GETS IT, in the STORED rows -- because a page nobody holds is invisible.
--
-- This is the trap 0151 exists for and it is worth restating: DEFAULT_PERMS in
-- the app is only a fallback for a role whose app_roles row is EMPTY, and every
-- role here has a populated row. So adding a module in code grants it to
-- NOBODY: the nav asks can('mod:/indoor'), the stored list lacks it, and the
-- page never appears -- with no error anywhere to explain why.
--
-- MERGED, NEVER OVERWRITTEN. An administrator may have tuned any of these roles
-- and a straight assignment would silently undo that.
--
-- WHO, AND WHY:
--   * admin / technical_support / zoho_migration -- every module key, by what
--     those roles ARE. The last two are read-only by what they do not hold:
--     the module key alone opens the page, and every write here is gated by an
--     action they have not got.
--   * nsm and spare_coordinator get the page and the working rights: the
--     workshop is theirs to run.
--   * indoor.condemn IS GRANTED TO NOBODY BUT ADMIN. Scrapping a machine --
--     customer property above all -- is not a default, it is a decision
--     somebody makes deliberately in Roles & Permissions. Open question 8 in
--     the plan asks who may condemn; until it is answered, the safe answer is
--     "whoever an administrator says", not "anyone who can open the page".
-- ---------------------------------------------------------------------------
do $indoor_perms$
declare
  r        record;
  v_add    jsonb;
begin
  if to_regclass('public.app_roles') is null then
    raise notice 'app_roles is missing -- run rbac.sql first';
    return;
  end if;

  for r in select role, permissions from public.app_roles loop
    v_add := '[]'::jsonb;

    if r.role in ('admin', 'technical_support', 'zoho_migration') then
      v_add := v_add || '["mod:/indoor"]'::jsonb;
    end if;
    if r.role = 'admin' then
      v_add := v_add || '["indoor.receive","indoor.work","indoor.qc","indoor.dispatch","indoor.condemn"]'::jsonb;
    end if;
    if r.role in ('nsm', 'spare_coordinator', 'stores_incharge') then
      v_add := v_add || '["mod:/indoor","indoor.receive","indoor.work","indoor.dispatch"]'::jsonb;
    end if;
    -- QC is separate from the work on purpose (4.5.6): giving both to the same
    -- role by default would make the segregation impossible to arrange later
    -- without taking something away from somebody.
    if r.role in ('nsm') then
      v_add := v_add || '["indoor.qc"]'::jsonb;
    end if;

    if jsonb_array_length(v_add) > 0 then
      update public.app_roles a
         set permissions = (
               select jsonb_agg(distinct p)
                 from jsonb_array_elements_text(coalesce(a.permissions, '[]'::jsonb) || v_add) t(p))
       where a.role = r.role;
    end if;
  end loop;
end $indoor_perms$;

