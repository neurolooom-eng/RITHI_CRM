-- ===========================================================================
-- INDOOR SERVICE — the workshop register (procedure §4.5). PHASE 1.
--
-- The plan is docs/INDOOR_SERVICE_PLAN.md and this is its Phase 1: the register
-- itself, standing alone. Phase 2 is the loop with the call (the transfer of
-- 4.5.1, the chip on the call, the completion report of 4.5.7); Phase 3 is QC
-- with acceptance criteria, which is what SR-006 actually asks for.
--
-- TWO AXES, NOT ONE, and this is the decision the whole shape rests on:
--
--   `kind`     -- WHOSE PROPERTY IS THIS. Customer property or a DEMO unit.
--                 It is not a label: it is what turns the custody duties of
--                 §7.5.10 on or off, which is precisely why the procedure gives
--                 DEMO units a different tag (4.5.5).
--   `activity` -- WHAT IS BEING DONE TO IT. Repair, Rework, Salvage,
--                 Pre-delivery inspection, Demo, Other.
--
-- One field cannot carry both. A pre-delivery check and a demo are both on the
-- company's own stock; a rework may be on either. Vignesh supplied four
-- activities and invited the split ("choose or creat ur own"): Repair is added
-- back because it is what §4.5 is actually about, and "recycling or rework" is
-- separated into Rework (§8.3.4, bringing a nonconforming unit back to spec)
-- and Salvage (SR-017, harvesting parts from a condemned one) — because calling
-- both by one word puts a scrapping decision and a repair decision in the same
-- bucket.
--
-- THE REGISTER IS NOT AN ATTRIBUTE OF A CALL. 4.5.5 puts DEMO units in here, and
-- a DEMO unit has no customer, no complaint and no call. So `ucn` is NULLABLE
-- and the register stands on its own; a call is "at Indoor Service" iff it has
-- an open row here, derived in one lookup the way UCN colours already are.
--
-- NO COLUMN IS ADDED TO THE THREE CALL TABLES AND THE `calls` VIEW IS NOT
-- REBUILT. That is not a shortcut, it is the safer road: `create or replace
-- view` drops `security_invoker`, which has silently exposed every call to every
-- user three times in this project (0040 -> 0050 -> 0057). Not rebuilding that
-- view avoids the whole class of fault.
--
-- WHAT THE PERMISSIONS ENFORCE, AND WHERE. The procedure separates the roles, so
-- the rights are separate: indoor.receive, indoor.work, indoor.qc,
-- indoor.dispatch, indoor.condemn. THREE OF THEM ARE ENFORCED BY A TRIGGER
-- BELOW, not by hiding buttons — this project has learned that a right the
-- database does not test is decoration (0126, 0127). `indoor.qc` being its own
-- right is the one that matters: it is what allows the check to be somebody
-- other than the person who did the work.
--
-- WHAT IS DELIBERATELY NOT ENFORCED, and why it is a warning rather than a
-- block: whether QC must be done by SOMEBODY ELSE. The procedure does not say
-- (open question 2 in the plan). Both names are recorded, so the segregation is
-- auditable either way and the screen warns when they match — turning that into
-- a hard block later is one line here, and unblocking a workshop that turns out
-- to have one qualified person is not.
--
-- A SALVAGED PART IS RECORDED, NOT CREDITED TO STOCK. Open question 7 has a real
-- risk attached: a harvested part entering hand stock under its normal code is
-- indistinguishable from a new one, and the condition grade becomes decoration.
-- Phase 1 therefore records the harvest and touches no balance. Recording
-- without crediting is the half that cannot go wrong.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- THE JOB NUMBER — IND<YY>-<NNNN>, restarting each year.
--
-- Its own series, because a DEMO unit has no UCN to be known by. Same shape as
-- the UCN counters (0125): one row per year, seeded PAST whatever that year
-- already carries, so it is safe to apply mid-year and correct after an import
-- that back-fills one. The year is INDIA'S -- `now()` is UTC and would roll the
-- year over at 5:30 am on 1 January, which is the same bug 0125 fixed for the
-- UCN's date.
--
-- RLS on with no policy: nothing but the definer function below may see or
-- touch it.
-- ---------------------------------------------------------------------------
create table if not exists public.indoor_job_counters (
  yr      smallint not null primary key,
  last_no integer  not null default 0
);
alter table public.indoor_job_counters enable row level security;

create or replace function public.next_indoor_job_no()
returns text language plpgsql volatile security definer set search_path = public as $$
declare
  v_yr  smallint := extract(year from (now() at time zone 'Asia/Kolkata'))::smallint;
  v_yy  text     := to_char((now() at time zone 'Asia/Kolkata'), 'YY');
  v_hi  integer;
  v_no  integer;
begin
  -- The highest number ALREADY ISSUED this year. The shape test matters as much
  -- as the prefix: an imported job_no that is not IND<YY>-<NNNN> has no number
  -- to compare, and right(job_no,4)::int on one would raise rather than skip it.
  select coalesce(max(right(job_no, 4)::int), 0) into v_hi
    from public.indoor_jobs
   where job_no like 'IND' || v_yy || '-%'
     and job_no ~ ('^IND' || v_yy || '-[0-9]{4}$');

  insert into public.indoor_job_counters (yr, last_no)
       values (v_yr, v_hi)
  on conflict (yr) do update
          set last_no = greatest(public.indoor_job_counters.last_no, excluded.last_no);

  update public.indoor_job_counters
     set last_no = last_no + 1
   where yr = v_yr
  returning last_no into v_no;

  return 'IND' || v_yy || '-' || lpad(v_no::text, 4, '0');
end $$;
revoke all on function public.next_indoor_job_no() from public;

-- ---------------------------------------------------------------------------
-- THE REGISTER. One row per equipment intake.
--
-- Wide on purpose. Six activities share a core -- everything §4.5 asks of every
-- unit that comes in -- and each adds fields only it needs. The alternative is
-- six tables that cannot be listed together, or a jsonb blob that nothing can
-- constrain; a register whose columns say what each activity owes is the one
-- that can be audited.
--
-- CLEANING APPLIES TO ALL SIX. A unit that has been in a hospital is
-- decontaminated before anyone opens it, whether it is going to be repaired,
-- stripped for parts or sent out on demo. WI/SER/01 does not care why it came in.
-- ---------------------------------------------------------------------------
create table if not exists public.indoor_jobs (
  id            bigint generated always as identity primary key,
  job_no        text not null unique,

  -- NULLABLE, and that is the point: a DEMO unit has no call.
  ucn           text,

  kind          text not null default 'Customer property'
                check (kind in ('Customer property', 'DEMO unit')),
  activity      text not null default 'Repair'
                check (activity in ('Repair', 'Rework', 'Salvage',
                                    'Pre-delivery inspection', 'Demo', 'Other')),

  product_name  text not null default '',
  serial        text not null default '',
  party_name    text,                       -- null for a DEMO unit with no customer

  -- 4.5.2 -- who received it, when.
  received_at   timestamptz not null default now(),
  received_by   uuid,
  condition_on_arrival text not null default '',
  tag_no        text not null default '',   -- 4.5.4 / 4.5.5, the physical tag

  status        text not null default 'Received'
                check (status in ('Received', 'Cleaned', 'Under repair',
                                  'Awaiting spares', 'QC', 'Ready',
                                  'Dispatched', 'Closed', 'Condemned')),

  -- 4.5.3 -- cleaned and disinfected per WI/SER/01, and against WHICH revision.
  cleaned_at    timestamptz,
  cleaned_by    uuid,
  cleaning_wi   text not null default 'WI/SER/01',
  cleaning_wi_rev text not null default '',

  work_done     text not null default '',
  findings      text not null default '',

  -- 4.5.6 -- the quality check is its OWN record, not a line in the work text.
  qc_result     text check (qc_result in ('Pass', 'Fail')),
  qc_by         uuid,
  qc_at         timestamptz,
  qc_notes      text not null default '',

  -- 4.5.7
  dispatched_at timestamptz,
  dispatched_by uuid,
  dispatch_ref  text not null default '',

  -- §7.5.10's reporting duty, which otherwise has nowhere to live: damage to
  -- the customer's property is theirs to be told about.
  damage_note   text not null default '',
  reported_to_customer_at timestamptz,
  reported_to_customer_by uuid,

  -- ---- Rework (§8.3.4) ---------------------------------------------------
  nc_reference           text not null default '',
  rework_instruction     text not null default '',
  rework_instruction_rev text not null default '',
  rework_authorised_by   text not null default '',
  rework_authorised_at   timestamptz,
  -- §8.3.4 ASKS FOR THIS EXPLICITLY and it is the field most likely to be left
