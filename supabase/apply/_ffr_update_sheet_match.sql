), n as (
  select s.*, regexp_replace(upper(s.ffr_no), '\s', '', 'g') as fk, upper(btrim(s.ucn)) as uk from s
), f as (
  select regexp_replace(upper(ffr_no), '\s', '', 'g') as fk, upper(btrim(ucn)) as uk, id, product_serial, imported_from from public.field_failure_reports
), m as (
  select n.fk, n.uk,
         (select count(*) from f where f.fk = n.fk and f.uk = n.uk) as by_both,
         (select count(*) from f where f.fk = n.fk) as by_no
    from n
)
select 1 as k, 'sheet pairs' as what, count(*)::text as n from m
union all select 2, 'match exactly one register row on FFR No + UCN', count(*) filter (where by_both = 1)::text from m
union all select 3, 'match several rows on FFR No + UCN', count(*) filter (where by_both > 1)::text from m
union all select 4, 'no row on FFR No + UCN, but the FFR No exists', count(*) filter (where by_both = 0 and by_no > 0)::text from m
union all select 5, 'FFR No not on the register at all', count(*) filter (where by_no = 0)::text from m
union all select 6, 'register rows', (select count(*) from f)::text
union all select 7, 'register rows with blank UCN', (select count(*) from f where uk = '')::text
union all select 10 + row_number() over (order by fk), 'no match sample: ' || fk || ' / ' || uk, by_no::text
  from (select * from m where by_both = 0 order by fk limit 25) z
