-- THE CUSTOMER ANSWERED, AND NOBODY FILED THE REPORT.
--
--   The user, 2026-09-22: "If a Customer Feedback is Present for the Said
--   Call, there should be a Report which is Solved - Report Completed. If it
--   is not Present then list it."
--
-- It is a consistency check between two records that cannot both be right when
-- they disagree. A feedback form is filled in AFTER a visit -- somebody went,
-- did the work and asked the customer what they thought of it -- so a call
-- carrying feedback and no completed report is a visit that happened and was
-- never written up. The feedback is the evidence that the work occurred; the
-- report is the record of it.
--
-- FOUR FINDINGS, NOT ONE, and they need different fixes -- the same argument as
-- 0224, and the reason `missing` names the one that applies rather than the
-- report simply listing rows:
--
--   the feedback records no UCN ....... nothing can be checked against it. The
--                                       feedback is real and unattached; it is
--                                       listed so it is not silently dropped
--                                       from a report about missing records.
--   no call with that UCN ............. the feedback names a call this system
--                                       does not have. Load the call, or the
--                                       UCN is wrong.
--   no visit at all ................... the call has no `reports` row. Load the
--                                       visit (Bulk Uploads -> Visit Reports).
--   a visit exists but none is
--   "Solved - Report Completed" ....... the commonest one, and the only one
--                                       where the answer is on screen already:
--                                       `latest_visit_status` says what it
--                                       reads instead, so the reader can tell
--                                       "Solved - Report Pending" (a known
--                                       absence) from "Unsolved" (a different
--                                       problem entirely).
--
-- ONE RULE FOR "COMPLETED", AND IT IS NOT A STRING COMPARISON. The status is
-- typed, imported and exported, so it arrives as `Solved - Report Completed`,
-- with a trailing space, in lower case, and with an en-dash. `Root_Import_All`
-- carried the trailing-space spelling in all 378 rows. is_report_completed()
-- reduces to lower-case alphanumerics before comparing, which is exactly what
-- `isCompletedVisit` in src/lib/reportMapping.ts does -- and `check:mapping`
-- now holds the two against each other, because a rule with two copies is a
-- rule with two answers.
--
-- A `security_invoker` VIEW, so the ordinary call and feedback policies decide
-- the rows. The SCREEN is what is restricted to administrators
-- (`mod:/feedback-without-report`); the view does not invent a second rule.
-- ===========================================================================

create or replace function public.is_report_completed(p_status text)
returns boolean
language sql immutable as $$
  -- Lower-case alphanumerics only. The CLIENT COPY is `isCompletedVisit` in
  -- src/lib/reportMapping.ts and the two must stay identical in effect.
  select lower(regexp_replace(coalesce(p_status, ''), '[^a-zA-Z0-9]', '', 'g'))
         = 'solvedreportcompleted';
$$;

grant execute on function public.is_report_completed(text) to authenticated;

comment on function public.is_report_completed(text) is
  'Is this visit status the call''s COMPLETED report? Compares lower-case alphanumerics only, so a trailing space, a lower-case spelling and an en-dash all read the same. Client copy: isCompletedVisit() in src/lib/reportMapping.ts.';

drop view if exists public.feedback_without_report;
create view public.feedback_without_report as
with fb as (
  -- The feedback's own normalised key. `ucn_key` on the table cannot be used
  -- for the join: it falls back to 'row-<id>' where the UCN is blank, which
  -- would match nothing and hide the "no UCN" finding behind a "no call"
  -- finding instead.
  select f.id, f.ucn, f.call_number, f.call_type, f.party_name, f.product_name,
         f.serial, f.state, f.engineer, f.complaint, f.visit_at, f.entry_at,
         nullif(lower(btrim(coalesce(f.ucn, ''))), '') as k
    from public.feedback f
),
latest as (
  -- THE LATEST ENTRY, matching sync_call_last_visit() (0032) -- the visit the
  -- call's own status comes from, so it is the one a reader sees.
  select distinct on (lower(btrim(r.ucn)))
         lower(btrim(r.ucn)) as k, r.uid, r.visit_at, r.updated_at,
         r.call_status, r.manual_report, r.engineer
    from public.reports r
   order by lower(btrim(r.ucn)), r.updated_at desc nulls last, r.id desc
),
done as (
  -- ANY visit on the call, not just the latest: a call whose completed report
  -- was filed first and then re-visited is not missing a report.
  select distinct lower(btrim(r.ucn)) as k
    from public.reports r
   where public.is_report_completed(r.call_status)
)
select
  f.id                                             as feedback_id,
  f.ucn,
  f.call_number,
  f.call_type,
  f.party_name,
  f.product_name,
  f.serial,
  f.state,
  f.engineer                                       as feedback_engineer,
  f.complaint,
  f.visit_at                                       as feedback_visit_at,
  f.entry_at                                       as feedback_entered_at,
  c.reg_date,
  c.open_state,
  l.uid                                            as latest_visit_uid,
  l.visit_at                                       as latest_visit_at,
  l.updated_at                                     as latest_visit_entry_at,
  l.call_status                                    as latest_visit_status,
  coalesce(nullif(btrim(coalesce(l.engineer, '')), ''), '') as visit_engineer,
  nullif(btrim(coalesce(l.manual_report, '')), '') as service_report,
  case
    when f.k is null      then 'the feedback records no UCN'
    when c.ucn is null    then 'no call with that UCN'
    when l.k is null      then 'no visit at all'
    else 'a visit exists but none reads Solved - Report Completed'
  end                                              as missing
from fb f
left join public.calls c on lower(btrim(c.ucn)) = f.k
left join latest l       on l.k = f.k
where f.k is null
   or not exists (select 1 from done d where d.k = f.k);

