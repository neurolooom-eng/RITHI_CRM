-- 0066_master_values_active.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- Master value lists gain an ACTIVE flag, as the part catalogue already has.
--
-- A value that is no longer used cannot simply be deleted: it is already on
-- calls, reports and spare requests, and removing it would leave those records
-- referring to something that no longer exists. Deactivating keeps the history
-- and takes the value out of the pickers — the same rule the parts catalogue
-- follows, and the same rule the rest of this system follows for records that
-- matter.
-- ===========================================================================

alter table public.masters
  add column if not exists active boolean not null default true;

create index if not exists masters_active_idx on public.masters (name, active);

-- ------------------------------------------------------------------------
-- 0067_master_list_permissions.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- Master value lists — permission per list, not one switch for all of them.
--
-- 0008 put every master write behind a single global `masters.edit`: whoever
-- could maintain Call Type could also maintain Cancel Reason, Feedback and
-- every list added since. Roles & Permissions now lists each master as its own
-- page, so the database has to honour the same granularity:
--
--   master.<list>.edit     add / change values in that one list
--   master.<list>.delete   remove a value from that one list
--
-- `masters.edit` still grants both on every list, so no existing role loses
-- anything — it is the parent the per-list keys inherit from (mirrors can() in
-- src/lib/auth.tsx, where mod:/masters covers every mod:/masters/<key>).
--
-- Only `public.masters` is split this way. parties / products / parts are their
-- own registers with their own screens and keep the global `masters.edit`.
-- ===========================================================================

do $$
begin
  if to_regclass('public.masters') is null then
    raise notice 'public.masters is not present — run the masters bundle first';
    return;
  end if;

  -- 0008 created one FOR ALL policy; replace it with per-command policies so
  -- delete can be granted separately from add / edit.
  drop policy if exists masters_write on public.masters;
  drop policy if exists masters_admin_write on public.masters;
  drop policy if exists masters_insert on public.masters;
  drop policy if exists masters_update on public.masters;
  drop policy if exists masters_delete on public.masters;

  create policy masters_insert on public.masters for insert
    with check (public.has_perm('masters.edit')
             or public.has_perm('master.' || coalesce(name, '') || '.edit'));

  create policy masters_update on public.masters for update
    using      (public.has_perm('masters.edit')
             or public.has_perm('master.' || coalesce(name, '') || '.edit'))
    with check (public.has_perm('masters.edit')
             or public.has_perm('master.' || coalesce(name, '') || '.edit'));

  create policy masters_delete on public.masters for delete
    using      (public.has_perm('masters.edit')
             or public.has_perm('master.' || coalesce(name, '') || '.delete'));
end $$;

-- ------------------------------------------------------------------------
-- 0076_party_key.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- PARTY KEY — a readable identifier for each customer: Party-1, Party-2, …
--
-- Two things at once, and the second matters more than it looks:
--
--   1. Every party gets a short, stable handle to refer to. Assigned ONCE on
--      insert and never reassigned — a key that moves is not a key.
--
--   2. `parties` had NO unique constraint at all, so re-running an upload
--      ADDED another copy of every row. On a 5,874-row master that is a
--      catastrophe you only notice later, when the pickers show everything
--      twice. `name_key` makes the party name the natural key, so a re-load
--      CORRECTS rather than duplicates.
--
-- `name_key` is a STORED generated column rather than an expression index,
-- because `on conflict` cannot infer an expression index — the upload's upsert
-- would be refused outright. (The same trap 0071 and 0074 sprang.)
-- ===========================================================================

alter table public.parties add column if not exists party_key text;
alter table public.parties
  add column if not exists name_key text generated always as (lower(btrim(party_name))) stored;

-- ---------------------------------------------------------------------------
-- The series. A table rather than a sequence, so the go-live reset can empty it
-- with the other counters and production starts again at Party-1 — a sequence
-- would have to be reset separately and would be forgotten.
-- ---------------------------------------------------------------------------
create table if not exists public.party_key_seq (
  singleton boolean primary key default true check (singleton),
  last_no   bigint not null default 0
);

create or replace function public.next_party_key()
returns text language plpgsql security definer set search_path = public as $$
declare v_no bigint;
begin
  insert into public.party_key_seq (singleton, last_no)
  values (true, coalesce((select max(nullif(regexp_replace(party_key, '^Party-', ''), '')::bigint)
                            from public.parties where party_key ~ '^Party-[0-9]+$'), 0))
  on conflict (singleton) do nothing;

  update public.party_key_seq set last_no = last_no + 1 returning last_no into v_no;
  return 'Party-' || v_no;
end $$;
grant execute on function public.next_party_key() to authenticated;

create or replace function public.parties_before_write()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'UPDATE' then
    -- A key that moves is not a key: keep whatever the row was given.
    new.party_key := coalesce(nullif(btrim(old.party_key), ''), new.party_key);
  end if;
  new.party_name := btrim(coalesce(new.party_name, ''));
  return new;
end $$;

drop trigger if exists parties_biu on public.parties;
create trigger parties_biu before insert or update on public.parties
  for each row execute function public.parties_before_write();

-- ---------------------------------------------------------------------------
-- The key is assigned AFTER the insert, not before it — and that is the whole
-- point of putting it here.
--
-- A BEFORE INSERT trigger fires on every attempted insert, INCLUDING the ones
-- that `on conflict do update` then turns into updates. Re-uploading the
-- 5,874-row Party Master would burn 5,874 numbers each time and the next real
-- party would come out as Party-11749 — a series with holes the size of the
-- file. AFTER INSERT fires only for rows that were genuinely inserted, so the
-- numbering follows the parties, not the upload attempts.
-- ---------------------------------------------------------------------------
create or replace function public.parties_after_insert()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if btrim(coalesce(new.party_key, '')) = '' then
    update public.parties set party_key = public.next_party_key() where id = new.id;
  end if;
  return null;
end $$;

drop trigger if exists parties_aii on public.parties;
create trigger parties_aii after insert on public.parties
  for each row execute function public.parties_after_insert();

-- Backfill anything already loaded, oldest first so the numbering follows the
-- order the parties were actually created.
do $$
declare r record;
begin
  for r in select id from public.parties
            where coalesce(btrim(party_key), '') = '' order by id loop
    update public.parties set party_key = public.next_party_key() where id = r.id;
  end loop;
end $$;

create unique index if not exists parties_party_key_uniq on public.parties (party_key)
  where party_key is not null;
-- THE point of the exercise: a second upload of the same file corrects its rows
-- instead of adding 5,874 more.
create unique index if not exists parties_name_key_uniq on public.parties (name_key);
create index if not exists parties_party_key_idx on public.parties (party_key);

-- ------------------------------------------------------------------------
-- 0079_part_product_keys.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- Natural keys for Part Master and Product Master.
--
-- Neither had one, so re-running an upload ADDED every row again — 1,324 parts
-- and 19,259 machines, silently, with the damage only visible later when every
-- picker shows everything twice. Parties got this in 0076; these are the other
-- two registers a cutover loads more than once.
--
--   parts     — the part CODE. One duplicate in the real 1,324-row export
--               ("YR134500"), which the upload collapses to the last of them.
--   products  — a machine is its MODEL plus its SERIAL, not the serial alone:
--               in the real 20,999-row export 3,794 serials repeat (there are
--               eleven machines called "219"), but model + serial is distinct
--               on 19,253 of 19,259.
--
-- Both are STORED generated columns rather than expression indexes, because
-- `on conflict` cannot infer an expression index (0071, 0074, 0076, 0077 — this
-- is the fifth time, hence the check in `npm run check:uploads`).
--
-- GUARDED: a project that already holds duplicates from an earlier load cannot
-- build the index, and this says so rather than failing the whole bundle.
-- ===========================================================================

alter table public.parts
  add column if not exists code_key text generated always as (lower(btrim(code))) stored;

do $$
begin
  if exists (select 1 from public.parts where btrim(coalesce(code, '')) <> ''
              group by lower(btrim(code)) having count(*) > 1) then
    raise notice 'parts already holds duplicate codes — de-duplicate, then re-run this file to build parts_code_key_uniq.';
  else
    create unique index if not exists parts_code_key_uniq on public.parts (code_key) where code_key <> '';
  end if;
end $$;

alter table public.products
  add column if not exists machine_key text generated always as
    (lower(btrim(coalesce(item_name, ''))) || '|' || lower(btrim(coalesce(serial_number, '')))) stored;

do $$
begin
  if exists (select 1 from public.products where btrim(coalesce(serial_number, '')) <> ''
              group by lower(btrim(coalesce(item_name, ''))) || '|' || lower(btrim(coalesce(serial_number, '')))
              having count(*) > 1) then
    raise notice 'products already holds duplicate model+serial — de-duplicate, then re-run this file to build products_machine_key_uniq.';
  else
    create unique index if not exists products_machine_key_uniq
      on public.products (machine_key) where machine_key <> '|';
  end if;
end $$;

create index if not exists parts_code_key_idx    on public.parts (code_key);
create index if not exists products_machine_idx  on public.products (machine_key);

commit;
