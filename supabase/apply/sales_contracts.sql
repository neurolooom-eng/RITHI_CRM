-- 0233_installation_call_wording.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- "INSTALLATION CALL" — ONE SPELLING, ON THE MASTER AND ON THE CALLS ALREADY
-- RAISED.
--
-- The user, 2026-09-23: "STANDARD COMPLAINT= INSTALLATION CALL , Reported
-- Complaint= INSTALLATION CALL". The Warranty Register wrote "Installation
-- Calls" until now.
--
-- WHY THIS IS A MIGRATION AND NOT JUST A CONSTANT IN THE CLIENT. Standard
-- Complaint is the dimension every count, filter and frequent-failure match
-- groups by, so a second spelling does not read as a typo: it SPLITS the total
-- silently and the reader believes both halves. Changing the client alone
-- would leave the installation calls raised before today under the old words
-- and every new one under the new ones, with nothing anywhere saying so.
--
-- TWO THINGS, AND THE FIRST IS THE ONE THAT IS EASY TO FORGET:
--
--   1. THE MASTER. `masters` is what the Standard Complaint picker offers, and
--      that field takes NO free text (the user's standing rule) -- so a value
--      the master has not got is a value nobody can choose and, on a call
--      opened in the form, a field that cannot show what the record holds.
--      The old value is LEFT ON THE MASTER rather than removed: a master row
--      is not a record, but deleting it would stop the picker offering a value
--      that historical calls still carry, and a filter built on it would
--      silently return nothing.
--
--   2. THE CALLS. Only INSTALLATION calls, and only those whose complaint is
--      that exact old phrase -- matched case-insensitively and space-squashed,
--      since an import may have written "Installation  Calls". A FIELD CALL
--      that happens to say "Installation Calls" is somebody's own words on
--      their own call and is NOT touched: this migration knows about the
--      calls THIS APPLICATION generated, and rewriting a value on a quality
--      record it did not write is a different act needing a different reason.
--
-- The call's own `complaint_date` / `breakdown_date` / `call_number` are NOT
-- back-filled. Those exist on the calls already raised and carry whatever was
-- right at the time; inventing a WI- number for a call raised before the rule
-- existed would be writing a fact that was never true.
-- ===========================================================================

-- ---- 1. the master -------------------------------------------------------
do $$
declare
  v_name text;
begin
  if to_regclass('public.masters') is null then
    raise notice '0233: masters is missing — the Standard Complaint value is not seeded.';
    return;
  end if;

  -- WHICHEVER NAME THIS PROJECT USES. `listMaster` reads BOTH 'complaint' and
  -- 'standardComplaint' for this picker, and which one a given project was
  -- seeded with is a fact about the data, not about this repository. The value
  -- goes beside the rows that are already there, so it appears in the same list.
  select m.name into v_name
    from public.masters m
   where m.name in ('complaint', 'standardComplaint')
   group by m.name
   order by count(*) desc
   limit 1;

  if v_name is null then v_name := 'standardComplaint'; end if;

  if not exists (
    select 1 from public.masters
     where name in ('complaint', 'standardComplaint')
       and upper(btrim(regexp_replace(value, '\s+', ' ', 'g'))) = 'INSTALLATION CALL'
  ) then
    insert into public.masters (name, value) values (v_name, 'INSTALLATION CALL');
    raise notice '0233: added "INSTALLATION CALL" to the % master.', v_name;
  end if;
end $$;

-- ---- 2. the installation calls already raised ----------------------------
do $$
declare
  n bigint;
begin
  if to_regclass('public.calls') is null then
    raise notice '0233: calls is missing — nothing to move.';
    return;
  end if;

  update public.calls c
     set standard_complaint = case
           when upper(btrim(regexp_replace(coalesce(c.standard_complaint, ''), '\s+', ' ', 'g'))) = 'INSTALLATION CALLS'
             then 'INSTALLATION CALL' else c.standard_complaint end,
         complaint_reported = case
           when upper(btrim(regexp_replace(coalesce(c.complaint_reported, ''), '\s+', ' ', 'g'))) = 'INSTALLATION CALLS'
             then 'INSTALLATION CALL' else c.complaint_reported end
   where upper(coalesce(c.call_type, '')) like 'INSTALL%'
     and (upper(btrim(regexp_replace(coalesce(c.standard_complaint, ''), '\s+', ' ', 'g'))) = 'INSTALLATION CALLS'
       or upper(btrim(regexp_replace(coalesce(c.complaint_reported, ''), '\s+', ' ', 'g'))) = 'INSTALLATION CALLS');

  get diagnostics n = row_count;
  raise notice '0233: % installation call(s) moved to "INSTALLATION CALL".', n;
end $$;

-- ------------------------------------------------------------------------
-- 0234_inst_call_is_a_call.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- `INST Call` HOLDS A CALL NUMBER OR NOTHING.
--
-- The user, 2026-09-23: "Yes clear the placeholder and map the UCN there."
--
-- WHAT WAS IN THERE. The AppSheet cover export fills `INST Call` with the
-- literal words "To Check" — the sheet's way of saying NOBODY HAS LOOKED YET,
-- which is the opposite of "this machine has its installation call". The
-- importer (`coverImport.ts`) copies the cell straight through, so a large part
-- of `sale_items` carries it. It read as a call number to every screen that
-- asked "has this machine got one?", which is what hid the ＋ Installation call
-- button on almost the whole Warranty Register (v0.9.351 fixed the reading;
-- this fixes the data).
--
-- THREE THINGS, AND THE THIRD IS WHY THIS IS NOT A ONE-OFF SCRIPT:
--
--   1. MAP the UCN where an installation call for that machine already exists.
--   2. CLEAR what is left that is not a call number.
--   3. A TRIGGER, so the next import cannot put it back — and, more important,
--      cannot DESTROY a UCN this application wrote.
--
-- THE THIRD IS THE ONE THAT MATTERS MOST. `coverImport` upserts on `uid`, so
-- re-importing the AppSheet file overwrites `inst_call` with whatever the cell
-- says. Without the trigger, this repair is undone by the next import — and a
-- machine whose call was raised in the app since the file was exported would
-- have its UCN replaced by "To Check", which is worse than the state being
-- fixed here, because the UCN is then gone and the call is orphaned.
--
-- THE TRIGGER DISCARDS RATHER THAN REFUSES, which is the 0113/0114 rule: a
-- refusal makes an honest importer fail on a file it cannot help, while
-- discarding makes a careless one harmless. It never clears a call number, and
-- it never invents one.
--
-- NOTHING IS THROWN AWAY. `inst_call_repair_log` keeps every old value beside
-- the new one, so this is reversible and inspectable — the placeholder is being
-- destroyed on a register of 1,500+ machines and "we replaced it with nothing"
-- is not an answer anybody can check.
-- ===========================================================================

-- ---- the shape of a call number -------------------------------------------
-- `next_ucn` (0001) builds YY + month letter A-L + DD + a type letter + four
-- digits: 26I23I0080. The CLIENT's copy is `isCallNumber()` in coverspec.ts and
-- `check:ui` holds the two together.
create or replace function public.is_call_number(p_value text)
returns boolean language sql immutable as $$
  select coalesce(btrim(p_value), '') ~* '^[0-9]{2}[A-L][0-9]{2}[A-Z][0-9]{4}$';
$$;

comment on function public.is_call_number(text) is
  'Is this a UCN this system issued (YY + month letter + DD + type letter + 4 digits), rather than a note somebody left? "To Check" is not.';

-- ---- the log ---------------------------------------------------------------
create table if not exists public.inst_call_repair_log (
  id            bigint generated always as identity primary key,
  sale_item_id  bigint not null,
  sa_number     text not null default '',
  product_name  text not null default '',
  serial_number text not null default '',
  old_value     text not null default '',
  new_value     text not null default '',
  why           text not null default '',
  changed_at    timestamptz not null default now()
);
comment on table public.inst_call_repair_log is
  'Every INST Call value 0234 changed, with the value it replaced. Kept so the repair is reversible and checkable.';

alter table public.inst_call_repair_log enable row level security;
drop policy if exists inst_call_repair_log_read on public.inst_call_repair_log;
create policy inst_call_repair_log_read on public.inst_call_repair_log for select
  using (public.is_admin());
grant select on public.inst_call_repair_log to authenticated;

-- ---- 1. MAP the UCN where the call already exists ---------------------------
--
-- A MACHINE IS ITS MODEL AND ITS SERIAL, never the serial alone (eleven
-- machines on this register are numbered 219). So the match is on BOTH.
--
-- EXACTLY ONE, OR NOTHING. Where two installation calls name the same machine
-- -- a re-installation, or a duplicate -- there is no way to say which one this
-- field means, and writing either would be a guess recorded as a fact. Those
-- are LEFT as they are and counted in the notice, so somebody can look.
--
-- Compared with `upper(btrim(...))` on both sides and NOT space-squashed:
-- trimming is a normalisation, squashing would make 'MONNAL  T60' match
-- 'MONNAL T60', which is a WIDENING and a different decision.
do $$
declare
  n_mapped bigint := 0;
  n_ambig  bigint := 0;
begin
  if to_regclass('public.sale_items') is null or to_regclass('public.calls') is null then
    raise notice '0234: sale_items or calls is missing — nothing mapped.';
    return;
  end if;

  with one_call as (
    select upper(btrim(c.product_name)) as p,
           upper(btrim(c.serial))       as s,
           min(c.ucn)                   as ucn,
           count(*)                     as n
      from public.calls c
     where upper(coalesce(c.call_type, '')) like 'INSTALL%'
       and btrim(coalesce(c.product_name, '')) <> ''
       and btrim(coalesce(c.serial, ''))       <> ''
       and public.is_call_number(c.ucn)
     group by 1, 2
  ),
  target as (
    select si.id, si.sa_number, si.product_name, si.serial_number,
           coalesce(si.inst_call, '') as old_value, oc.ucn
      from public.sale_items si
      join one_call oc
        on oc.p = upper(btrim(coalesce(si.product_name, '')))
       and oc.s = upper(btrim(coalesce(si.serial_number, '')))
     where oc.n = 1
       -- A machine already carrying a real UCN is left alone: whatever is there
       -- was written by somebody or by this application, and is not this
       -- migration's to second-guess.
       and not public.is_call_number(si.inst_call)
  ),
  logged as (
    insert into public.inst_call_repair_log
      (sale_item_id, sa_number, product_name, serial_number, old_value, new_value, why)
    select t.id, coalesce(t.sa_number, ''), coalesce(t.product_name, ''),
           coalesce(t.serial_number, ''), t.old_value, t.ucn,
           'mapped to the existing installation call for this model + serial'
      from target t
    returning sale_item_id, new_value
  )
  update public.sale_items si
     set inst_call = l.new_value
    from logged l
   where si.id = l.sale_item_id;

  get diagnostics n_mapped = row_count;

  select count(*) into n_ambig from (
    select 1
      from public.calls c
     where upper(coalesce(c.call_type, '')) like 'INSTALL%'
       and btrim(coalesce(c.product_name, '')) <> ''
       and btrim(coalesce(c.serial, ''))       <> ''
     group by upper(btrim(c.product_name)), upper(btrim(c.serial))
    having count(*) > 1) x;

  raise notice '0234: % machine(s) mapped to their existing installation call.', n_mapped;
  if n_ambig > 0 then
    raise notice '0234: % machine(s) have MORE THAN ONE installation call and were left alone — pick one by hand.', n_ambig;
  end if;
end $$;

-- ---- 2. CLEAR what is left that is not a call number ------------------------
--
-- EVERYTHING that is not a UCN, not only the words "To Check". The field's
-- meaning is now "the installation call for this machine, or nothing", and a
-- note left in it reads as a call number to anything that looks. Every value
-- removed is in the log above, which is what makes clearing the honest option
-- rather than the destructive one.
do $$
declare
  n bigint := 0;
begin
  if to_regclass('public.sale_items') is null then return; end if;

  with calls_for as (
    select upper(btrim(c.product_name)) as p,
           upper(btrim(c.serial))       as s,
           count(*)                     as n,
           string_agg(c.ucn, ', ' order by c.ucn) as ucns
      from public.calls c
     where upper(coalesce(c.call_type, '')) like 'INSTALL%'
       and btrim(coalesce(c.product_name, '')) <> ''
       and btrim(coalesce(c.serial, ''))       <> ''
       and public.is_call_number(c.ucn)
     group by 1, 2
  ),
  target as (
    select si.id, si.sa_number, si.product_name, si.serial_number,
           coalesce(si.inst_call, '') as old_value,
           -- WHY IT IS BLANK, PER ROW. A machine with SEVERAL installation
           -- calls is cleared like any other -- "To Check" is not a call number
           -- whatever else is true -- but it is NOT the same situation as a
           -- machine with none, and the register cannot tell them apart once
           -- both read empty. The one that matters ends up offered a button
           -- that would raise a THIRD call, so the log has to name it: this
           -- table IS the list somebody works from.
           case when coalesce(cf.n, 0) > 1
                then 'not a call number — cleared, but ' || cf.n
                     || ' installation calls already name this machine (' || cf.ucns
                     || '): pick one by hand'
                else 'not a call number — cleared so the machine can be offered one' end as why
      from public.sale_items si
      left join calls_for cf
        on cf.p = upper(btrim(coalesce(si.product_name, '')))
       and cf.s = upper(btrim(coalesce(si.serial_number, '')))
     where btrim(coalesce(si.inst_call, '')) <> ''
       and not public.is_call_number(si.inst_call)
  ),
  logged as (
    insert into public.inst_call_repair_log
      (sale_item_id, sa_number, product_name, serial_number, old_value, new_value, why)
    select t.id, coalesce(t.sa_number, ''), coalesce(t.product_name, ''),
           coalesce(t.serial_number, ''), t.old_value, '', t.why
      from target t
    returning sale_item_id
  )
  update public.sale_items si
     set inst_call = ''
    from logged l
   where si.id = l.sale_item_id;

  get diagnostics n = row_count;
  raise notice '0234: % placeholder(s) cleared from INST Call.', n;
end $$;

-- ---- 3. KEEP IT THAT WAY ----------------------------------------------------
create or replace function public.sale_item_inst_call_guard()
returns trigger language plpgsql set search_path = public as $$
begin
  -- A value that is not a call number is not stored. "To Check" reads as a call
  -- number to every screen that asks whether this machine has one.
  if not public.is_call_number(new.inst_call) then
    new.inst_call := '';
  end if;

  -- AND A CALL NUMBER IS NEVER REPLACED BY NOTHING. `coverImport` upserts on
  -- `uid`, so re-importing the AppSheet file would otherwise wipe the UCN of
  -- every call raised in the app since that file was exported — leaving the
  -- call with no machine pointing at it and no trace of the loss. The import is
  -- not refused: it simply cannot take this one column backwards.
  --
  -- A DBA IN THE SQL EDITOR CAN, and the test is `current_user` -- the same one
  -- `block_hard_delete` (0049) uses, for the same reason. This guard exists to
  -- stop a careless CLIENT, not an approved correction: when a call is DELETED
  -- the mapping to it stops being true, and a guard that preserved it would
  -- leave the machine reading "this one has its installation call" for ever,
  -- pointing at a UCN that does not exist. Found by writing
  -- `_delete_these_calls.sql` and watching this branch put the value back while
  -- the report said it had been cleared.
  if tg_op = 'UPDATE'
     and current_user = 'authenticated'
     and public.is_call_number(old.inst_call)
     and coalesce(new.inst_call, '') = '' then
    new.inst_call := old.inst_call;
  end if;

  return new;
end $$;

drop trigger if exists zz_sale_item_inst_call_guard on public.sale_items;
create trigger zz_sale_item_inst_call_guard
  before insert or update of inst_call on public.sale_items
  for each row execute function public.sale_item_inst_call_guard();

comment on function public.sale_item_inst_call_guard() is
  'INST Call holds a UCN or nothing: a non-call value is discarded rather than refused (the 0113/0114 rule), and a re-import can never replace a real UCN with a blank.';

-- ------------------------------------------------------------------------
-- 0236_cover_policies_are_initplans.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- THE COVER POLICIES ARE ASKED ONCE PER QUERY, NOT ONCE PER ROW.
--
-- Found by EXPLAIN, after "Search failed: canceling statement due to statement
-- timeout" on the Product Database (2026-09-23). The plan named it exactly:
--
--   Seq Scan on contract_items ci  (actual time=16209.182..16209.182 rows=0)
--     Filter: (has_perm('cover.edit') OR has_perm('masters.view')
--              OR has_perm('cover.edit') OR is_admin())
--     Rows Removed by Filter: 20001
--
-- SIXTEEN SECONDS TO RETURN NOTHING. The predicate says nothing about the row
-- -- it is the same answer for every row in the table -- but written bare it is
-- a per-row expression, so Postgres called has_perm() four times for each of
-- 20,001 rows and each call reads app_roles.
--
-- WRAPPING IT IN A SCALAR SUBQUERY MAKES IT AN InitPlan: evaluated ONCE, at the
-- start, and the result reused. Identical semantics, identical audience --
-- nobody gains or loses a row. This project has now made the same fix three
-- times: 0095 on the hand-stock policies, 0164 on cr_read (measured at 1,840 ms
-- to 7.4 ms for an engineer), and here.
--
-- IT WAS NOT HURTING BEFORE because the cover registers always read with a
-- filter -- an SA number, a serial -- so the scan was small and 20,001
-- evaluations never happened. The Product Database reads the WHOLE install base
-- and joins these tables to it, which is what exposed it. A policy that is
-- fine until somebody writes a bigger query is not fine; it is waiting.
--
-- ALL FOUR TABLES AND BOTH POLICIES, because the write policy has the same
-- shape and the same fault -- an UPDATE over many rows pays it the same way.
-- ===========================================================================

do $$
declare t text;
begin
  foreach t in array array['sale_entries', 'sale_items', 'contract_entries', 'contract_items'] loop
    if to_regclass('public.' || t) is null then continue; end if;

    execute format('drop policy if exists %1$s_read on public.%1$s;', t);
    execute format($f$create policy %1$s_read on public.%1$s for select
                        using ((select public.has_perm('masters.view'))
                            or (select public.has_perm('cover.edit'))
                            or (select public.is_admin()));$f$, t);

    execute format('drop policy if exists %1$s_write on public.%1$s;', t);
    execute format($f$create policy %1$s_write on public.%1$s for all
                        using ((select public.has_perm('cover.edit')))
                        with check ((select public.has_perm('cover.edit')));$f$, t);
  end loop;
end $$;

-- ------------------------------------------------------------------------
-- 0237_sale_fills_product_database.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- A WARRANTY SALE PUTS ITS MACHINES INTO THE PRODUCT DATABASE.
--
-- The user, 2026-09-24: "Every time I add a Warranty Sale entry, all the
-- products should get added to the product database. There is an opportunity
-- that same product is sold again to a different customer, in that case the old
-- data should be over written. All fields should get updated in product
-- database as per the warranty sale details."
--
-- WHAT WAS THERE ALREADY, AND WHY IT WAS NOT ENOUGH. `sale_items` has fired
-- `sync_product_cover()` since 0036, and that function does an UPDATE: it
-- refreshes the cover of a machine ALREADY in the register and does nothing at
-- all for one that is not. So a machine sold today appeared in the Product
-- Database only if the AppSheet import had happened to carry it. The register
-- of what exists was being kept by an import rather than by the act of selling.
--
-- AND IT KEYS ON THE SERIAL ALONE, which this project settled long ago:
-- A MACHINE IS ITS MODEL AND ITS SERIAL. The install base holds eleven machines
-- numbered 219, so a serial-only match writes one sale's cover onto a different
-- model. This keys on `machine_key` -- the generated lower(model)|lower(serial)
-- -- which is the same key `products_machine_key_uniq` already enforces.
--
-- RE-SOLD TO A DIFFERENT CUSTOMER IS THE CASE THE ASK NAMES, and it falls out
-- of the key: the same model and serial is the same machine, so the upsert
-- finds the existing row and the new sale's party, dates and location replace
-- the previous owner's. That is the whole point -- the Product Database says
-- who has the machine NOW.
--
-- WHAT IT WRITES IS WHAT THE SALE KNOWS, AND ONLY THAT.
--
--   written:  party, model, serial, product code, SA number, warranty start /
--             end / status, PM visits, sold through, state, city, address,
--             other details, the sale's engineer, and the installation call.
--   NOT written: everything about the CONTRACT (the sale knows nothing about
--             it and a blank would erase real cover), `extra` (the import's
--             kept columns), `item_status` (worked out on read since 0235, and
--             the stored value is the migrated system's own answer, preserved
--             deliberately as item_status_keyed), and `active`.
--
-- A BLANK ON THE SALE IS WRITTEN AS A BLANK, and that is deliberate rather than
-- careless: "all fields ... as per the warranty sale details" is the ask, and on
-- a RE-SALE the alternative is worse -- keeping the previous owner's city
-- against the new owner's machine is not stale data, it is wrong data about
-- somebody else.
--
-- ONE THING THIS CHANGES THAT NOBODY ASKED FOR, said plainly rather than
-- buried: an OWNERSHIP TRANSFER also writes products.party_name, and a later
-- edit to the sale will now overwrite it with the sale's party. The transfer
-- row is untouched and the machine's history is intact, but the Product
-- Database would show the original buyer again. It only happens if somebody
-- edits that sale after the transfer; if that is wrong for this business, the
-- rule to add is "do not overwrite the party where a transfer is dated after
-- the sale", and it is one clause.
-- ===========================================================================

create or replace function public.upsert_product_from_sale(p_item_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare i record; h record;
begin
  select * into i from public.sale_items where id = p_item_id;
  if not found then return; end if;

  -- A MACHINE IS ITS MODEL AND ITS SERIAL. A line with either missing is not a
  -- machine yet -- a half-typed row on an open entry -- and putting it in the
  -- install base would create a product nobody can identify.
  if btrim(coalesce(i.product_name, '')) = '' or btrim(coalesce(i.serial_number, '')) = '' then
    return;
  end if;

  select * into h from public.sale_entries where sa_number = i.sa_number;

  insert into public.products as p (
    item_name, serial_number, party_name,
    item_code, warranty_number,
    warranty_start, warranty_end, warranty_status_keyed, pm_visits,
    sold_through, state, city, address, other_details,
    service_engineer, inst_call)
  values (
    btrim(i.product_name), btrim(i.serial_number), coalesce(h.party_name, ''),
    coalesce(i.product_code, ''), coalesce(i.sa_number, ''),
    -- The EFFECTIVE value: the machine's own where it pinned one, else the
    -- entry's. That is the inheritance the registers already show on screen
    -- (0036), so the Product Database agrees with what the operator is reading.
    coalesce(i.warranty_start, h.warranty_start),
    coalesce(i.warranty_end,   h.warranty_end),
    coalesce(nullif(btrim(coalesce(i.warranty_status, '')), ''), h.warranty_status, ''),
    coalesce(i.pm_visits, h.pm_visits),
    coalesce(nullif(btrim(coalesce(i.sold_through, '')), ''), h.sold_through, ''),
    coalesce(nullif(btrim(coalesce(i.state, '')), ''), h.state, ''),
    coalesce(nullif(btrim(coalesce(i.city,  '')), ''), h.city,  ''),
    coalesce(h.address, ''),
    coalesce(nullif(btrim(coalesce(i.other_details, '')), ''), h.other_details, ''),
    coalesce(nullif(btrim(coalesce(i.engineer, '')), ''), h.engineer, ''),
    coalesce(i.inst_call, ''))
  on conflict (machine_key) do update set
    party_name            = excluded.party_name,
    item_code             = excluded.item_code,
    warranty_number       = excluded.warranty_number,
    warranty_start        = excluded.warranty_start,
    warranty_end          = excluded.warranty_end,
    warranty_status_keyed = excluded.warranty_status_keyed,
    pm_visits             = excluded.pm_visits,
    sold_through          = excluded.sold_through,
    state                 = excluded.state,
    city                  = excluded.city,
    address               = excluded.address,
    other_details         = excluded.other_details,
    service_engineer      = excluded.service_engineer,
    -- THE ONE FIELD THAT IS NEVER TAKEN BACKWARDS. 0234's rule: a UCN already
    -- on the machine is a call that exists, and a sale re-saved with a blank
    -- INST Call would orphan it. A real UCN on the sale still replaces one.
    inst_call             = case when public.is_call_number(excluded.inst_call)
                                 then excluded.inst_call else p.inst_call end;
end $$;

comment on function public.upsert_product_from_sale(bigint) is
  'Puts one Warranty Sale machine into the Product Database, keyed on MODEL + SERIAL, overwriting what the sale knows and leaving the contract, `extra` and item_status alone.';

