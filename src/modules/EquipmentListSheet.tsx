// ===========================================================================
// THE EQUIPMENT LIST -- the document Product & Party Search exports (the user,
// 2026-10-15: "Give an option to export this into a List. Apply Air Liquide
// Logo and generate a template ... It should have details of Who generated the
// list, when. Header, footer to explicitly mention this as Confidential
// information"; asked: a PDF; the header "Logo, Equipment list").
//
// PURE: rows and the facts about the print come in as props, so the same sheet
// is what the print page shows and what the sample template is rendered from.
// The header and the footer are the table's own <thead> / <tfoot>, so a
// browser repeats both on EVERY printed page; the page number is the
// printer's (@page), since a web page cannot number its own sheets.
// The cover in force today is highlighted GREEN (the user: "Highlight in
// Green"), printed in colour (print-color-adjust).
// ===========================================================================
import { COMPANY_LOGO } from '../lib/brand';
import { contractActive, coverEndingIn, currentItemStatus, warrantyActive } from '../lib/coverToday';
import { formatDay } from '../lib/dates';
import './equipmentlist.css';

type Row = Record<string, unknown>;
const s = (r: Row, k: string) => String(r[k] ?? '').trim();

export interface EquipmentListMeta {
  filterLabel: string;          // "Expiring this month (Oct-2026)"
  narrowedBy: string;           // " of MONNAL T75" / " at CITY HOSPITAL" / ''
  generatedBy: string;          // the person's name and email
  generatedAt: string;          // dd-MMM-yyyy HH:mm:ss
  today: string;                // yyyy-mm-dd: what "active" and "current" mean
  ending?: { from: string; to: string };   // a month filter's window
}

export const EQUIPMENT_LIST_CONFIDENTIAL = 'CONFIDENTIAL INFORMATION';
export const EQUIPMENT_LIST_FOOTER = 'Confidential Information — Air Liquide Medical Systems. For internal use only; not to be shared outside the organisation.';

export function EquipmentListSheet({ rows, meta }: { rows: Row[]; meta: EquipmentListMeta }) {
  const cols = 15 + (meta.ending ? 1 : 0);
  const on = (active: boolean, text: string) => (active && text ? <span className="el-on">{text}</span> : text);
  return (
    <table className="el-table">
      <thead>
        <tr>
          <th colSpan={cols} className="el-headcell">
            <div className="el-head">
              <img className="el-logo" src={COMPANY_LOGO} alt="Air Liquide" />
              <div className="el-title">Equipment List</div>
              <div className="el-conf">{EQUIPMENT_LIST_CONFIDENTIAL}</div>
            </div>
            <div className="el-meta">
              <span><b>List:</b> {meta.filterLabel}{meta.narrowedBy}</span>
              <span><b>Machines:</b> {rows.length}</span>
              <span><b>Generated by:</b> {meta.generatedBy}</span>
              <span><b>Generated on:</b> {meta.generatedAt}</span>
            </div>
          </th>
        </tr>
        <tr className="el-cols">
          <th className="el-n">#</th>
          <th>Product</th><th>Serial</th><th>Party</th><th>City</th>
          {meta.ending && <th>Ending</th>}
          <th>Warranty No</th><th>Warranty Start</th><th>Warranty End</th>
          <th>Contract No</th><th>Contract Start</th><th>Contract End</th><th>Type</th>
          <th>Current Status</th><th>OT No</th>
        </tr>
      </thead>
      <tfoot>
        <tr>
          <td colSpan={cols} className="el-footcell">
            <span>{EQUIPMENT_LIST_FOOTER}</span>
            <span>Generated by {meta.generatedBy} on {meta.generatedAt}</span>
          </td>
        </tr>
      </tfoot>
      <tbody>
        {rows.map((r, i) => {
          const w = warrantyActive(r, meta.today);
          const c = contractActive(r, meta.today);
          return (
            <tr key={i}>
              <td className="el-n">{i + 1}</td>
              <td>{s(r, 'Item Name')}</td>
              <td className="el-nw">{s(r, 'Item Serial Number')}</td>
              <td>{s(r, 'Party Name')}</td>
              <td>{s(r, 'City')}</td>
              {meta.ending && <td className="el-nw">{coverEndingIn(r, meta.ending.from, meta.ending.to).replace(/\d{4}-\d{2}-\d{2}/g, (d) => formatDay(d))}</td>}
              <td className="el-nw">{on(w, s(r, 'Warranty Number'))}</td>
              <td className="el-nw">{on(w, formatDay(s(r, 'Warranty Start Date')))}</td>
              <td className="el-nw">{on(w, formatDay(s(r, 'Warranty End Date')))}</td>
              <td className="el-nw">{on(c, s(r, 'Contract Number'))}</td>
              <td className="el-nw">{on(c, formatDay(s(r, 'Contract Start Date')))}</td>
              <td className="el-nw">{on(c, formatDay(s(r, 'Contract End Date')))}</td>
              <td className="el-nw">{on(c, s(r, 'Contract Type'))}</td>
              <td className="el-nw"><b>{currentItemStatus(r, meta.today)}</b></td>
              <td className="el-nw">{s(r, 'Transfer Ref')}</td>
            </tr>
          );
        })}
        {rows.length === 0 && <tr><td colSpan={cols} className="el-empty">No machine is in this list.</td></tr>}
      </tbody>
    </table>
  );
}
