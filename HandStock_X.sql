-- With partial dispatch (0055) a line can arrive in several deliveries, so
-- "received" stopped being one moment per line. The engineer now acknowledges
-- each SHIPMENT: every spare_dispatch_lines row is stamped when it lands, and
-- the line carries how much has been acknowledged so far (received_qty).
--
-- The line's own received_at is still what marks it Received — it is set only
-- once the WHOLE line has been acknowledged — so spare_line_stage() and
-- deriveStage() are untouched: a line part-delivered stays at Stores (waiting
-- for its balance) and turns Received when the last unit is confirmed.
-- ===========================================================================

alter table public.spare_request_lines
  add column if not exists received_qty numeric not null default 0;

alter table public.spare_dispatch_lines
  add column if not exists received_at     timestamptz,
  add column if not exists received_by     text default '',
  add column if not exists receipt_remarks text default '';

-- History: a line already acknowledged had all of it acknowledged, and its
-- shipments landed with it. Idempotent.
update public.spare_request_lines l
   set received_qty = coalesce(l.qty, 0)
 where l.received_at is not null and coalesce(l.received_qty, 0) = 0;

update public.spare_dispatch_lines d
   set received_at = l.received_at,
       received_by = coalesce(l.received_by, '')
  from public.spare_request_lines l
 where l.id = d.line_id and d.received_at is null and l.received_at is not null;

-- ---------------------------------------------------------------------------
-- Acknowledge every outstanding shipment on these lines. Returns how many
-- shipments were acknowledged. A line whose whole quantity is now confirmed is
-- closed as Received; one still awaiting a balance stays where it is.
-- ---------------------------------------------------------------------------
create or replace function public.receive_spare_shipments(
  p_line_ids bigint[],
  p_actor    text default '',
  p_remarks  text default ''
) returns integer
language plpgsql security definer set search_path = public as $$
declare n integer := 0; lid bigint; got numeric;
begin
  if not (public.is_admin() or public.has_perm('spare.receive')) then
    raise exception 'RBAC: acknowledging a receipt requires the spare.receive permission';
  end if;
  if p_line_ids is null or array_length(p_line_ids, 1) is null then
    raise exception 'Nothing to acknowledge: no spares selected';
  end if;

  foreach lid in array p_line_ids loop
    update public.spare_dispatch_lines d
       set received_at     = now(),
           received_by     = coalesce(nullif(btrim(p_actor), ''), ''),
           receipt_remarks = coalesce(p_remarks, '')
     where d.line_id = lid and d.received_at is null;
    get diagnostics got = row_count;
    n := n + got;

    -- how much of this line has now been acknowledged
    select coalesce(sum(d.qty), 0) into got
      from public.spare_dispatch_lines d
     where d.line_id = lid and d.received_at is not null;

    update public.spare_request_lines l
       set received_qty = got,
           -- only a fully acknowledged line becomes Received
           received_at     = case when got >= coalesce(l.qty, 0) then now() else l.received_at end,
           received_by     = case when got >= coalesce(l.qty, 0)
                                  then coalesce(nullif(btrim(p_actor), ''), '') else l.received_by end,
           receipt_remarks = case when got >= coalesce(l.qty, 0)
                                  then coalesce(p_remarks, '') else l.receipt_remarks end
     where l.id = lid;
  end loop;

  return n;
end $$;
grant execute on function public.receive_spare_shipments(bigint[], text, text) to authenticated;

-- ------------------------------------------------------------------------
-- 0059_consumption_reconciliation.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- RECONCILIATION CONSUMPTION — an Admin / Spare Coordinator can book a spare
-- against a call directly into consumption, without waiting for the engineer's
-- call report.
--
-- These rows are stock adjustments made by the office, not something the
-- engineer wrote, so they are FLAGGED: `source` is 'Reconciliation' rather than
-- the default 'Report'. Hand stock already treats consumption as stock leaving
-- the engineer's hands, so a reconciliation line corrects the balance the same
-- way a reported one does — the flag is what keeps the two tellable apart.
--
-- Guarded by its own permission (consumption.reconcile) so an engineer cannot
-- write one, and stamped with who entered it. spare_consumption is already an
-- audited table (0048), so every reconciliation carries a full before/after
-- trail.
-- ===========================================================================

alter table public.spare_consumption
  add column if not exists source      text not null default 'Report',   -- Report | Reconciliation
  add column if not exists remarks     text default '',                  -- why the adjustment was made
  add column if not exists recorded_by text default '';                  -- who entered it (name)

create index if not exists spare_consumption_source_idx on public.spare_consumption (source);

-- Stamp the author so the register's Created By stops coming back empty.
create or replace function public.consumption_before_insert()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.created_by is null then new.created_by := auth.uid(); end if;
  if coalesce(new.source, '') = '' then new.source := 'Report'; end if;
  return new;
end $$;
drop trigger if exists consumption_biu on public.spare_consumption;
create trigger consumption_biu before insert on public.spare_consumption
  for each row execute function public.consumption_before_insert();

-- Writing a RECONCILIATION line needs the new permission; an ordinary reported
-- line keeps the existing rule (the engineer reporting, or Stores).
drop policy if exists cons_write on public.spare_consumption;
create policy cons_write on public.spare_consumption for insert
  with check (
    case when coalesce(source, 'Report') = 'Reconciliation'
         then public.has_perm('consumption.reconcile')
         else (public.has_perm('calls.report') or public.has_perm('spare.dispatch'))
    end
  );

-- Grant it to the roles that do the reconciling: Spare Coordinator, Hotline
-- and Admin (merge — anything already tuned on these roles is kept).
do $$
declare r text;
begin
  foreach r in array array['admin', 'spare_coordinator', 'hotline'] loop
    insert into public.app_roles as ar (role, label, permissions)
    values (r, initcap(replace(r, '_', ' ')), '["consumption.reconcile"]'::jsonb)
    on conflict (role) do update set
      permissions = (
        select coalesce(jsonb_agg(distinct v), '[]'::jsonb)
        from (
          select jsonb_array_elements_text(ar.permissions) as v
          union
          select 'consumption.reconcile' as v
        ) u
      ),
      updated_at = now();
  end loop;
end $$;

-- ------------------------------------------------------------------------
-- 0060_reconcile_within_handstock.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- A reconciliation is booked AGAINST A CALL, and cannot consume more than the
-- engineer is holding.
--
-- The office books these lines by hand, so the quantity is typed rather than
-- derived — and a typo would drive an engineer's hand stock negative and
-- quietly corrupt the balance every stock screen reads. The picker only offers
-- parts in that engineer's hand stock, and this guard is the same rule enforced
-- where it cannot be bypassed.
--
-- Only RECONCILIATION rows are capped. A consumption reported from a call is
-- left alone: that is the engineer stating what they actually fitted, and the
-- honest answer to it exceeding the recorded balance is to fix the balance, not
-- to refuse the report.
-- ===========================================================================

create or replace function public.consumption_reconcile_guard()
returns trigger language plpgsql security definer set search_path = public as $$
declare avail numeric;
begin
  if coalesce(new.source, 'Report') <> 'Reconciliation' then return new; end if;
  if coalesce(new.qty, 0) <= 0 then
    raise exception 'Quantity must be more than zero';
  end if;

  -- The UCN is what makes this traceable to a call; without it the line is an
  -- unattributed stock write-off. Required, and it has to be a real call.
  if coalesce(btrim(new.ucn), '') = '' then
    raise exception 'A reconciliation needs the UCN of the call the spare was used on';
  end if;
  if not exists (select 1 from public.calls c where c.ucn = btrim(new.ucn)) then
    raise exception 'No call found with UCN % — check the number', btrim(new.ucn);
  end if;

  -- Every field is required on a hand-booked line: whose stock it came off,
  -- what was used, and why. A stock adjustment with no stated reason is not
  -- auditable, which is the whole point of flagging these separately.
  if coalesce(btrim(new.engineer), '') = '' then
    raise exception 'A reconciliation needs the engineer whose hand stock the spare came off';
  end if;
  if coalesce(btrim(new.part), '') = '' then
    raise exception 'A reconciliation needs the part';
  end if;
  if coalesce(btrim(new.remarks), '') = '' then
    raise exception 'A reconciliation needs a reason (why the spare is being booked by hand)';
  end if;

  select coalesce(b.on_hand, 0) into avail
    from public.handstock_balance b
   where b.engineer_key = public.handstock_key(coalesce(new.engineer, ''))
     and b.part_code    = public.part_code(coalesce(new.part, ''));

  if coalesce(avail, 0) < new.qty then
    raise exception '% has % of % in hand — cannot book % against this call',
      coalesce(nullif(btrim(new.engineer), ''), 'That engineer'),
      coalesce(avail, 0), public.part_code(coalesce(new.part, '')), new.qty;
  end if;
  return new;
end $$;

-- Runs after consumption_biu ('c' < 'r'), so `source` is defaulted before the
-- guard reads it.
drop trigger if exists consumption_reconcile_guard on public.spare_consumption;
create trigger consumption_reconcile_guard before insert on public.spare_consumption
  for each row execute function public.consumption_reconcile_guard();

-- ------------------------------------------------------------------------
-- 0061_cap_all_consumption.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- No consumption may exceed the engineer's hand stock — reported or not.
--
-- 0060 capped only the office's reconciliation lines and deliberately left a
-- call report uncapped, on the reasoning that the engineer is stating what they
-- actually fitted. In practice an engineer can simply key it wrong, and a wrong
-- report drives the balance negative where nobody is watching.
--
-- So the cap now applies to EVERY consumption line. When a report is refused,
-- the fix belongs to the Spare Coordinator: correct the hand stock (dispatch,
-- transfer, or a reconciliation line) and the report goes through. Control of
-- the balance sits with the coordinator, not with whoever typed last.
--
-- Unattributable rows are the one exception: with no engineer or no part there
-- is no balance to check, so those are allowed rather than blocked — refusing
-- them would strand a call report on a data gap the engineer cannot fix.
-- Mandatory UCN / engineer / reason stay specific to reconciliation lines.
-- ===========================================================================

create or replace function public.consumption_reconcile_guard()
returns trigger language plpgsql security definer set search_path = public as $$
declare avail numeric; is_recon boolean;
begin
  is_recon := coalesce(new.source, 'Report') = 'Reconciliation';

  if coalesce(new.qty, 0) <= 0 then
    raise exception 'Quantity must be more than zero';
  end if;

  -- Everything is required on a hand-booked line: whose stock it came off,
  -- what was used, and why. A stock adjustment with no stated reason is not
  -- auditable, which is the point of flagging these separately.
  if is_recon then
    if coalesce(btrim(new.ucn), '') = '' then
      raise exception 'A reconciliation needs the UCN of the call the spare was used on';
    end if;
    if not exists (select 1 from public.calls c where c.ucn = btrim(new.ucn)) then
      raise exception 'No call found with UCN % — check the number', btrim(new.ucn);
    end if;
    if coalesce(btrim(new.engineer), '') = '' then
      raise exception 'A reconciliation needs the engineer whose hand stock the spare came off';
    end if;
    if coalesce(btrim(new.part), '') = '' then
      raise exception 'A reconciliation needs the part';
    end if;
    if coalesce(btrim(new.remarks), '') = '' then
      raise exception 'A reconciliation needs a reason (why the spare is being booked by hand)';
    end if;
  end if;

  -- THE CAP — every line, however it was written. Skipped only when the row
  -- names no engineer or no part, where there is no balance to check.
  if coalesce(btrim(new.engineer), '') = '' or coalesce(btrim(new.part), '') = '' then
    return new;
  end if;

  select coalesce(b.on_hand, 0) into avail
    from public.handstock_balance b
   where b.engineer_key = public.handstock_key(new.engineer)
     and b.part_code    = public.part_code(new.part);

  if coalesce(avail, 0) < new.qty then
    if is_recon then
      raise exception '% has % of % in hand — cannot book % against this call',
        btrim(new.engineer), coalesce(avail, 0), public.part_code(new.part), new.qty;
    else
      raise exception
        '% has % of % in hand, so % cannot be consumed. Ask the Spare Coordinator to correct the hand stock first.',
        btrim(new.engineer), coalesce(avail, 0), public.part_code(new.part), new.qty;
    end if;
  end if;
  return new;
end $$;

drop trigger if exists consumption_reconcile_guard on public.spare_consumption;
create trigger consumption_reconcile_guard before insert on public.spare_consumption
  for each row execute function public.consumption_reconcile_guard();

-- ------------------------------------------------------------------------
-- 0062_adjust_consumption_qty.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- ADJUSTING A CONSUMPTION QUANTITY (part of reconciliation).
--
-- An engineer can report the wrong quantity, and until now nothing could put it
-- right: spare_consumption had no UPDATE policy at all, so the row was frozen
-- and the balance stayed wrong. The Spare Coordinator can now correct the
-- quantity — and only the quantity.
--
-- What is kept:
--   • on the row — original_qty, adjusted_by, adjusted_at and the reason, so
--     the correction is visible where the line is read;
--   • in the audit trail — record_audit (0048) already logs every UPDATE with
--     the full before/after, so nothing depends on the row being honest.
--
-- What cannot be changed: the call, the part, the engineer or the source. A
-- reconciliation corrects a NUMBER; letting it rewrite whose stock or which
-- call would turn an adjustment into a way of rewriting history. Change those
-- by dropping the line and booking the right one.
-- ===========================================================================

alter table public.spare_consumption
  add column if not exists original_qty      numeric,
  add column if not exists adjusted_by       text,
  add column if not exists adjusted_at       timestamptz,
  add column if not exists adjustment_reason text;

-- Correcting a line is the reconciler's job, same permission as booking one.
drop policy if exists cons_update on public.spare_consumption;
create policy cons_update on public.spare_consumption for update
  using (public.has_perm('consumption.reconcile'))
  with check (public.has_perm('consumption.reconcile'));

create or replace function public.consumption_adjust_guard()
returns trigger language plpgsql security definer set search_path = public as $$
declare avail numeric; delta numeric;
begin
  -- Identity is fixed: a reconciliation adjusts the quantity, nothing else.
  if coalesce(new.ucn, '')      is distinct from coalesce(old.ucn, '')
  or coalesce(new.part, '')     is distinct from coalesce(old.part, '')
  or coalesce(new.engineer, '') is distinct from coalesce(old.engineer, '')
  or coalesce(new.source, '')   is distinct from coalesce(old.source, '') then
    raise exception 'A reconciliation can only change the quantity — not the call, part, engineer or source';
  end if;

  if new.qty is not distinct from old.qty then
    return new;                        -- nothing quantitative changed
  end if;
  if coalesce(new.qty, 0) <= 0 then
    raise exception 'Quantity must be more than zero';
  end if;
  if coalesce(btrim(new.adjustment_reason), '') = '' then
    raise exception 'Say why the quantity is being adjusted — the reason is kept with the line';
  end if;

  -- Raising it consumes more stock: the extra has to be in hand. on_hand
  -- already accounts for the quantity this line consumes today, so only the
  -- DELTA is checked. Lowering it always gives stock back.
  delta := new.qty - old.qty;
  if delta > 0 and coalesce(btrim(new.engineer), '') <> '' and coalesce(btrim(new.part), '') <> '' then
    select coalesce(b.on_hand, 0) into avail
      from public.handstock_balance b
     where b.engineer_key = public.handstock_key(new.engineer)
       and b.part_code    = public.part_code(new.part);
    if coalesce(avail, 0) < delta then
      raise exception '% has % of % in hand — cannot raise this line from % to %',
        btrim(new.engineer), coalesce(avail, 0), public.part_code(new.part), old.qty, new.qty;
    end if;
  end if;

  -- Keep what it was before the FIRST adjustment, and stamp who/when.
  if new.original_qty is null then new.original_qty := old.qty; end if;
  new.adjusted_at := now();
  if coalesce(btrim(new.adjusted_by), '') = '' then
    new.adjusted_by := coalesce((select full_name from public.profiles where id = auth.uid()), '');
  end if;
  return new;
end $$;

drop trigger if exists consumption_adjust_guard on public.spare_consumption;
create trigger consumption_adjust_guard before update on public.spare_consumption
  for each row execute function public.consumption_adjust_guard();

-- ------------------------------------------------------------------------
-- 0063_void_consumption_line.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- VOIDING a consumption line — setting the quantity to zero.
--
-- A spare booked against the wrong call, or never actually fitted, has to come
-- off the balance. Deleting the row is not an option and should not be: these
-- are quality records, hard deletes are blocked (0049), and a line that simply
-- vanishes takes its history with it.
--
-- So a line is VOIDED instead: the quantity goes to 0, the row stays, and the
-- original quantity, the reason and who did it stay with it. Hand stock treats
-- a zero-quantity line as consuming nothing, so the spare returns to the
-- engineer's balance — which is exactly what "it was never used" means.
--
-- Creating a line at zero is still refused: an entry that consumes nothing is
-- not something to write in the first place. Zero is only reachable by voiding
-- something that already exists.
-- ===========================================================================

create or replace function public.consumption_adjust_guard()
returns trigger language plpgsql security definer set search_path = public as $$
declare avail numeric; delta numeric;
begin
  if coalesce(new.ucn, '')      is distinct from coalesce(old.ucn, '')
  or coalesce(new.part, '')     is distinct from coalesce(old.part, '')
  or coalesce(new.engineer, '') is distinct from coalesce(old.engineer, '')
  or coalesce(new.source, '')   is distinct from coalesce(old.source, '') then
    raise exception 'A reconciliation can only change the quantity — not the call, part, engineer or source';
  end if;

  if new.qty is not distinct from old.qty then
    return new;
  end if;
  -- 0 is allowed here (voiding); negative never is.
  if coalesce(new.qty, 0) < 0 then
    raise exception 'Quantity cannot be negative — set it to 0 to void the line';
  end if;
  if coalesce(btrim(new.adjustment_reason), '') = '' then
    raise exception 'Say why the quantity is being adjusted — the reason is kept with the line';
  end if;

  delta := new.qty - old.qty;
  if delta > 0 and coalesce(btrim(new.engineer), '') <> '' and coalesce(btrim(new.part), '') <> '' then
    select coalesce(b.on_hand, 0) into avail
      from public.handstock_balance b
     where b.engineer_key = public.handstock_key(new.engineer)
       and b.part_code    = public.part_code(new.part);
    if coalesce(avail, 0) < delta then
      raise exception '% has % of % in hand — cannot raise this line from % to %',
        btrim(new.engineer), coalesce(avail, 0), public.part_code(new.part), old.qty, new.qty;
    end if;
  end if;

  if new.original_qty is null then new.original_qty := old.qty; end if;
  new.adjusted_at := now();
  if coalesce(btrim(new.adjusted_by), '') = '' then
    new.adjusted_by := coalesce((select full_name from public.profiles where id = auth.uid()), '');
  end if;
  return new;
end $$;

-- ------------------------------------------------------------------------
-- 0064_stock_out_lines_and_refurb.sql
-- ------------------------------------------------------------------------

-- ===========================================================================
-- STOCK OUT — a flat line list, time-to-dispatch, and refurbished parts.
--
-- 1. spare_stock_out_lines: one row per spare actually issued, rather than one
--    card per stock out. It carries the call and the order it came from, and
--    DAYS TO DISPATCH — measured from the moment the spare cleared its LAST
--    approval (NSM where the item needs that review, else Commercial, else RM)
--    to the moment Stores booked it out. That is the interval Stores actually
--    controls; counting from the request would measure the approvers instead.
--
-- 2. Refurbished parts. A recycled spare carries the same description under an
--    R-prefixed part number (ECG-022 -> RECG-022). Stores records the swap as
--    it books the spare out; the DC and the engineer's notification then both
--    say plainly that the part is refurbished.
--
--    NOTE: hand stock continues to key on the REQUESTED part code, so balances
--    and consumption are unaffected by the swap. The refurbished identity is
--    recorded on the issue and shown to the engineer. Tracking R-parts as
--    separate stock lines would be a further change.
-- ===========================================================================

alter table public.spare_dispatch_lines
  add column if not exists refurbished boolean not null default false;

-- ---- the flat list ---------------------------------------------------------
create or replace view public.spare_stock_out_lines as
select
  dl.id                                   as line_id,
  d.uid                                   as stock_out_no,
  coalesce(d.dc_number, '')               as dc_number,
  d.dc_date,
  d.dispatched_at,
  coalesce(d.dispatched_by, '')           as dispatched_by,
  coalesce(d.courier, '')                 as courier,
  coalesce(d.engineer, '')                as engineer,
  lower(btrim(coalesce(d.engineer, '')))  as engineer_key,
  coalesce(d.engineer_email, '')          as engineer_email,
  coalesce(dl.line_uid, '')               as line_uid,
  coalesce(dl.part, '')                   as part,
  public.part_code(dl.part)               as part_code,
  dl.qty,
  dl.refurbished,
  dl.received_at,
  coalesce(r.or_no, '')                   as or_no,
  coalesce(r.req_type, '')                as req_type,
  coalesce(r.item_status, '')             as item_status,
  coalesce(r.ucn, '')                     as ucn,
  coalesce(r.call_number, '')             as call_number,
  coalesce(r.party_name, '')              as party_name,
  coalesce(r.product_name, '')            as product_name,
  coalesce(r.serial, '')                  as serial,
  -- when it cleared its last approval and became Stores' to send
  coalesce(greatest(l.rm_at, l.commercial_at, l.nsm_at), l.created_at, r.created_at)
                                          as approved_at,
  -- and how long Stores then took, in days (one decimal)
  round(
    extract(epoch from (
      d.dispatched_at
      - coalesce(greatest(l.rm_at, l.commercial_at, l.nsm_at), l.created_at, r.created_at)
    ))::numeric / 86400.0, 1)              as days_to_dispatch
from public.spare_dispatch_lines dl
join public.spare_dispatches      d on d.uid = dl.dispatch_uid
join public.spare_request_lines   l on l.id  = dl.line_id
join public.spare_requests        r on r.uid = l.request_uid;

alter view public.spare_stock_out_lines set (security_invoker = on);
grant select on public.spare_stock_out_lines to authenticated;

-- ---- issuing a refurbished part -------------------------------------------
-- p_refurb is parallel to p_line_ids: true issues the recycled equivalent, so
-- the ISSUE records R<code> with the description unchanged. The request itself
-- is untouched — it still says what was asked for.
create or replace function public.refurb_part(p_part text)
returns text language sql immutable as $$
  select case
    when coalesce(btrim(p_part), '') = '' then p_part
    when public.part_code(p_part) like 'R%' then p_part          -- already recycled
    else 'R' || public.part_code(p_part)
         || case when position('|' in p_part) > 0
                 then '|' || split_part(p_part, '|', 2) else '' end
  end;
$$;
grant execute on function public.refurb_part(text) to authenticated;

-- Dispatch, now able to issue a line as its recycled equivalent.
create or replace function public.dispatch_spare_lines(
  p_line_ids bigint[],
  p_qtys     numeric[],
  p_refurb   boolean[],
  p_courier  text default '',
  p_remarks  text default '',
  p_dc_date  date default current_date,
  p_actor    text default ''
) returns public.spare_dispatches
language plpgsql security definer set search_path = public as $$
declare
  eng text; n integer; head public.spare_dispatches; email text;
  i integer; lid bigint; want numeric; rem numeric; send numeric; ref boolean;
  total numeric := 0; cnt integer := 0;
begin
  if not (public.is_admin() or public.has_perm('spare.dispatch')) then
    raise exception 'RBAC: dispatch requires the spare.dispatch permission';
  end if;
  if p_line_ids is null or array_length(p_line_ids, 1) is null then
    raise exception 'Nothing to dispatch: no spares selected';
  end if;

  select count(*), min(v.engineer), min(v.engineer_email) into n, eng, email
    from public.spare_pending_dispatch v where v.line_id = any (p_line_ids);
  if coalesce(n, 0) <> array_length(p_line_ids, 1) then
    raise exception
      'Only % of the % selected spares are still waiting at Stores — refresh and try again',
      coalesce(n, 0), array_length(p_line_ids, 1);
  end if;
  if (select count(distinct v.engineer_key) from public.spare_pending_dispatch v
       where v.line_id = any (p_line_ids)) <> 1 then
    raise exception 'A stock out goes to one engineer — select spares for a single engineer';
  end if;

  insert into public.spare_dispatches
    (dc_date, engineer, engineer_email, courier, remarks, line_count, total_qty, dispatched_by)
  values
    (coalesce(p_dc_date, current_date), eng, coalesce(email, ''), coalesce(p_courier, ''),
     coalesce(p_remarks, ''), 0, 0, coalesce(nullif(btrim(p_actor), ''), ''))
  returning * into head;

  for i in 1 .. array_length(p_line_ids, 1) loop
    lid  := p_line_ids[i];
    want := case when p_qtys   is null then null  else p_qtys[i]   end;
    ref  := case when p_refurb is null then false else coalesce(p_refurb[i], false) end;

    select greatest(coalesce(l.qty, 0) - coalesce(l.dispatched_qty, 0), 0)
      into rem from public.spare_request_lines l where l.id = lid;

    send := coalesce(want, rem);
    if send is null or send <= 0 then
      raise exception 'Quantity for spare % must be more than zero', lid;
    end if;
    if send > rem then
      raise exception 'Only % left to send on that spare (you asked for %) — refresh and try again', rem, send;
    end if;

    insert into public.spare_dispatch_lines (dispatch_uid, line_id, line_uid, part, qty, refurbished)
    select head.uid, l.id, coalesce(l.line_uid, ''),
           case when ref then public.refurb_part(l.part) else coalesce(l.part, '') end,
           send, ref
      from public.spare_request_lines l where l.id = lid;

    update public.spare_request_lines l
       set dispatched_qty   = coalesce(l.dispatched_qty, 0) + send,
           courier          = coalesce(p_courier, ''),
           dispatch_remarks = coalesce(p_remarks, ''),
           dispatched_by    = head.dispatched_by,
           dispatched_at    = head.dispatched_at,
           dc_number    = case when coalesce(l.dispatched_qty, 0) + send >= coalesce(l.qty, 0)
                               then head.dc_number else l.dc_number end,
           dispatch_uid = case when coalesce(l.dispatched_qty, 0) + send >= coalesce(l.qty, 0)
                               then head.uid else l.dispatch_uid end,
           stock_out_no = case when coalesce(l.dispatched_qty, 0) + send >= coalesce(l.qty, 0)
                               then head.uid else l.stock_out_no end,
           stores_status = case when coalesce(l.dispatched_qty, 0) + send >= coalesce(l.qty, 0)
                                then 'Dispatched' else l.stores_status end
     where l.id = lid;

    total := total + send; cnt := cnt + 1;
  end loop;

  update public.spare_dispatches d set line_count = cnt, total_qty = total
   where d.uid = head.uid returning * into head;
  return head;
end $$;
