  -- tiles, the digest) counts outstanding units, not the original ask.
  greatest(coalesce(l.qty, 0) - coalesce(l.dispatched_qty, 0), 0) as qty,
  r.req_type,
  r.item_status,
  coalesce(r.engineer, '')                    as engineer,
